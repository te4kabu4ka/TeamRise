  function simulateBusinessWeek() {
    const runs = 120;
    let executionAcc = 0;
    let growthAcc = 0;
    let burnoutAcc = 0;

    for (let i = 0; i < runs; i += 1) {
      const roleBoost = ROLE_BOOSTS[gameState.employee.team] || ROLE_BOOSTS['Sales Manager'];
      const sprintDiscipline = random(0.52, 0.91) * roleBoost.control;
      const execution = clamp(sprintDiscipline * 100 - random(5, 22), 20, 100);
      const growth = clamp(execution * 0.28 + random(3, 16), 0, 100);
      const burnout = clamp(70 - execution * 0.45 + random(-6, 10), 5, 96);
      executionAcc += execution;
      growthAcc += growth;
      burnoutAcc += burnout;
    }

    const executionAvg = executionAcc / runs;
    const growthAvg = growthAcc / runs;
    const burnoutAvg = burnoutAcc / runs;

    gameState.metrics.weeklyExecution = clamp((gameState.metrics.weeklyExecution + executionAvg) / 2, 0, 100);
    gameState.metrics.salesGrowth = clamp((gameState.metrics.salesGrowth + growthAvg) / 2, 0, 100);
    gameState.metrics.burnoutRisk = clamp((gameState.metrics.burnoutRisk + burnoutAvg) / 2, 0, 100);
    gameState.metrics.score += Math.round(growthAvg * 3.1);

    emitFloatText(`Симуляция недели: выполнение ${executionAvg.toFixed(1)}%, рост ${growthAvg.toFixed(1)}%`, 150, 120, '#22d3ee');
    updateKpiPanel();
  }

