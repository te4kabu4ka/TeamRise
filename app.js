    window.addEventListener('keydown', (e) => {
      switch (e.code) {
        case 'ArrowLeft':
        case 'KeyA': Input.left = true; break;
        case 'ArrowRight':
        case 'KeyD': Input.right = true; break;
        case 'ArrowUp':
        case 'Space':
        case 'KeyW': Input.jump = true; break;
        case 'ShiftLeft':
        case 'ShiftRight': Input.dash = true; break;
        case 'KeyE': Input.interact = true; break;
        case 'KeyP': gameState.paused = !gameState.paused; break;
        default: break;
      }
    });

    window.addEventListener('keyup', (e) => {
      switch (e.code) {
        case 'ArrowLeft':
        case 'KeyA': Input.left = false; break;
        case 'ArrowRight':
        case 'KeyD': Input.right = false; break;
        case 'ShiftLeft':
        case 'ShiftRight': Input.dash = false; break;
        case 'KeyE': Input.interact = false; break;
        default: break;
      }
    });

    ui.startBtn.addEventListener('click', () => {
      if (!gameState.employee.authorized) {
        ui.authStatus.textContent = 'Сначала войдите как сотрудник.';
        ui.authModal.classList.remove('hidden');
        return;
      }
      gameState.running = true;
      gameState.paused = false;
      gameState.over = false;
      gameState.victory = false;
    });

    ui.pauseBtn.addEventListener('click', () => { gameState.paused = !gameState.paused; });
