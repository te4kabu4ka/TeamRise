  function update(dt) {
    if (!gameState.running || gameState.paused || gameState.over || gameState.victory) return;

    gameState.time += dt;
    gameState.timers.obstacle += dt;
    gameState.timers.treasure += dt;
    gameState.timers.comboDecay += dt;
    gameState.timers.coach -= dt;
    gameState.timers.event -= dt;
    gameState.timers.sparkle -= dt;
    gameState.timers.lesson -= dt;

    const diff = DIFFICULTY_PRESETS[gameState.abMode];
    if (gameState.timers.obstacle > diff.obstacleSpawnMs) { gameState.entities.push(createTrap(WORLD.width + random(20, 80), WORLD.floorY - 46)); gameState.timers.obstacle = 0; }
    if (gameState.timers.treasure > diff.treasureSpawnMs) { gameState.entities.push(createTreasure(WORLD.width + random(0, 140), random(120, WORLD.floorY - 90))); gameState.timers.treasure = 0; }
    if (gameState.timers.comboDecay > diff.comboDecayMs && gameState.metrics.combo > 0) {
      gameState.metrics.combo -= 1;
      gameState.timers.comboDecay = 0;
      emitFloatText('Комбо тает: обнови фокус команды!', gameState.player.x, gameState.player.y - 20, '#f59e0b');
    }

    if (gameState.timers.coach <= 0) { gameState.coachLine = pick(COACH_QUOTES); gameState.timers.coach = random(2800, 6200); }
    if (gameState.timers.event <= 0) { triggerRandomEvent(); gameState.timers.event = random(4200, 8200); }
    if (gameState.timers.lesson <= 0) { showEducationPopup(); gameState.timers.lesson = random(6200, 10200); }
    if (gameState.timers.sparkle <= 0) { spawnAmbientParticles(); gameState.timers.sparkle = random(400, 900); }

    updatePlayer(dt);
    updateEntities(dt);
    updateParticles(dt);
    updateMetrics(dt);
    updateLevel();
  }

