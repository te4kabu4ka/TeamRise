  function render() {
    const shake = gameState.cameraShake;
    if (shake > 0) {
      const dx = random(-shake, shake);
      const dy = random(-shake, shake);
      ctx.save();
      ctx.translate(dx, dy);
    }

    renderBackground();
    renderEntities();
    renderPlayer();
    renderParticles();
    renderFloatTexts();
    renderUI();

    if (shake > 0) {
      ctx.restore();
      gameState.cameraShake = Math.max(0, shake - 1.2);
    }
  }

